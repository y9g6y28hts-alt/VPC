"""Centerlines of the surveyed road parcel (avenue and streets), for the
ambient traffic and walkers of the experience.

  python3 tools/survey/road-centerlines.py > js/data/road-centerlines.js

Rasterises ROADS from js/data/masterplan.js at 0.25 m, skeletonises it and
walks the skeleton into polylines (simplified to 0.3 m), keeping branches
longer than 12 m. Needs NumPy, shapely and scikit-image.
"""
import json
import re
import sys
from pathlib import Path

import numpy as np
from shapely.geometry import LineString, Polygon
from skimage.draw import polygon as fill
from skimage.morphology import skeletonize

ROOT = Path(__file__).resolve().parents[2]
src = (ROOT / 'js/data/masterplan.js').read_text()
roads = json.loads(re.search(r'export const ROADS = (\[.*?\]);', src).group(1))
poly = Polygon([(p['x'], p['z']) for p in roads]).buffer(0)

RES = 0.25
x0, z0, x1, z1 = poly.bounds
W = int((x1 - x0) / RES) + 3
H = int((z1 - z0) / RES) + 3
mask = np.zeros((H, W), bool)
geoms = getattr(poly, 'geoms', [poly])
for g in geoms:
    xs = (np.array(g.exterior.xy[0]) - x0) / RES + 1
    zs = (np.array(g.exterior.xy[1]) - z0) / RES + 1
    rr, cc = fill(zs, xs, mask.shape)
    mask[rr, cc] = True
    for hole in g.interiors:
        hx = (np.array(hole.xy[0]) - x0) / RES + 1
        hz = (np.array(hole.xy[1]) - z0) / RES + 1
        rr, cc = fill(hz, hx, mask.shape)
        mask[rr, cc] = False
sk = skeletonize(mask)

# Walk the skeleton: nodes are pixels with != 2 neighbours.
pts = set(zip(*np.nonzero(sk)))
def nbrs(p):
    r, c = p
    return [(r + dr, c + dc) for dr in (-1, 0, 1) for dc in (-1, 0, 1) if (dr or dc) and (r + dr, c + dc) in pts]
nodes = {p for p in pts if len(nbrs(p)) != 2}
seen = set()
lines = []
for n in nodes:
    for m in nbrs(n):
        if (n, m) in seen:
            continue
        path = [n, m]
        seen.add((n, m))
        prev, cur = n, m
        while cur not in nodes:
            nxt = [q for q in nbrs(cur) if q != prev and q not in path[-3:]]
            if not nxt:
                break
            prev, cur = cur, nxt[0]
            path.append(cur)
        seen.add((path[-1], path[-2]))
        line = LineString([(x0 + (c - 1) * RES, z0 + (r - 1) * RES) for r, c in path])
        if line.length >= 12:
            lines.append(line.simplify(0.3))

out = [[{'x': round(x, 2), 'z': round(z, 2)} for x, z in l.coords] for l in sorted(lines, key=lambda l: -l.length)]
print('// GENERATED by tools/survey/road-centerlines.py from the surveyed road parcel. Do not edit.')
print(f'// {len(out)} polylines, {sum(l.length for l in lines):.0f} m in total.')
print('export const ROAD_CENTERLINES = ' + json.dumps(out, separators=(',', ':')) + ';')
